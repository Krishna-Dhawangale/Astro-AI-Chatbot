def is_rate_limit_error(exc: Exception) -> bool:
    """Determines whether an exception is a rate limit or token exhaustion (HTTP 429)."""
    if isinstance(exc, GroqRateLimitError):
        return True
    if isinstance(exc, httpx.HTTPStatusError):
        if exc.response is not None and exc.response.status_code == 429:
            return True
    err_str = str(exc).lower()
    if hasattr(exc, "response") and getattr(exc, "response", None) is not None:
        try:
            err_str += " " + exc.response.text.lower()
        except Exception:
            pass
    rate_signals = (
        "429",
        "rate_limit",
        "rate limit",
        "ratelimit",
        "tokens per minute",
        "token limit",
        "tokens/min",
        "tpm",
        "requests per minute",
        "rpm",
        "quota exceeded",
        "resource_exhausted",
        "insufficient_quota",
    )
    return any(sig in err_str for sig in rate_signals)


def is_timeout_error(exc: Exception) -> bool:
    """Determines whether an exception is a network or client timeout."""
    if isinstance(exc, (GroqAPITimeoutError, httpx.TimeoutException, asyncio.TimeoutError)):
        return True
    err_str = str(exc).lower()
    return "timeout" in err_str or "timed out" in err_str

