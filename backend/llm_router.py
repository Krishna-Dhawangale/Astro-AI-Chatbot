class GroqAccountClient:
    """
    Asynchronous client wrapper representing an individual Groq account tier.
    Tracks rate limit cool-off state, failure metrics, and execution timing.
    """
    def __init__(self, account_id: str, api_key: str, tier: int):
        self.account_id: str = account_id  # e.g., "Groq-Account-1", "Groq-Account-2"
        self.api_key: str = api_key
        self.tier: int = tier
        self.rate_limited_until: float = 0.0
        self.total_requests: int = 0
        self.total_rate_limits: int = 0

    @property
    def is_rate_limited(self) -> bool:
        return time.perf_counter() < self.rate_limited_until

    def mark_rate_limited(self, cooloff_seconds: float = 60.0) -> None:
        self.rate_limited_until = time.perf_counter() + cooloff_seconds
        self.total_rate_limits += 1

    def reset_limit(self) -> None:
        self.rate_limited_until = 0.0

    def __repr__(self) -> str:
        return f"<GroqAccountClient {self.account_id} (Tier {self.tier}) limited={self.is_rate_limited}>"


class AsyncGroqRotationPool:
    """
    Multi-Account Groq Rotation Pool providing high-performance,
    millisecond-level API failover cascade across configured accounts.
    Supports sequential tier priority (Tier 1 -> Tier 2) and round-robin dispatch.
    """
    def __init__(self, accounts: Optional[List[GroqAccountClient]] = None):
        self.accounts: List[GroqAccountClient] = accounts or []
        self._round_robin_idx: int = 0
        self._lock = asyncio.Lock()

    @classmethod
    def from_env(cls) -> "AsyncGroqRotationPool":
        """Discovers and configures Groq accounts from environment variables."""
        key1 = (
            os.getenv("GROQ_API_KEY_1")
            or os.getenv("GROQ_API_KEY_ACCOUNT1")
            or os.getenv("GROQ_API_KEY_ACC1")
            or os.getenv("GROQ_API_KEY")
        )
        key2 = (
            os.getenv("GROQ_API_KEY_2")
            or os.getenv("GROQ_API_KEY_ACCOUNT2")
            or os.getenv("GROQ_API_KEY_ACC2")
        )
        accs: List[GroqAccountClient] = []
        if key1 and key1.strip():
            accs.append(GroqAccountClient(account_id="Groq-Account-1", api_key=key1.strip(), tier=1))
        if key2 and key2.strip() and key2.strip() != (key1 or "").strip():
            accs.append(GroqAccountClient(account_id="Groq-Account-2", api_key=key2.strip(), tier=2))
        return cls(accs)

    def get_accounts(self) -> List[GroqAccountClient]:
        """Returns accounts in sequential priority order (Tier 1 -> Tier 2)."""
        return list(self.accounts)

    async def get_next_round_robin_account(self) -> Optional[GroqAccountClient]:
        """Returns next available non-rate-limited account in round-robin sequence."""
        if not self.accounts:
            return None
        async with self._lock:
            for _ in range(len(self.accounts)):
                acc = self.accounts[self._round_robin_idx % len(self.accounts)]
                self._round_robin_idx += 1
                if not acc.is_rate_limited:
                    return acc
            return self.accounts[self._round_robin_idx % len(self.accounts)]


# Singleton Groq pool instance for global reuse
_GLOBAL_GROQ_POOL: Optional[AsyncGroqRotationPool] = None


