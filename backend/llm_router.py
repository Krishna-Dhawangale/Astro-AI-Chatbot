# Master Cascading Router with Safe Failover
# ---------------------------------------------------------------------------
async def stream_cascading_router(
    prompt: str,
    system_prompt: str,
    max_output_tokens: int = 120,
    temperature: float = 0.2,
    session_id: Optional[str] = None,
    history: Optional[List[Dict[str, Any]]] = None,
    custom_httpx_client: Optional[httpx.AsyncClient] = None,
    custom_gemini_client: Optional[Any] = None,
    local_fallback_text: Optional[str] = None,
) -> AsyncGenerator[Tuple[str, Dict[str, Any]], None]:
    """
    Cascades sequentially through:
      1. Groq Account 1 (Llama 3.3 70B -> Llama 3.1 8B)
      2. Groq Account 2 (Llama 3.3 70B -> Llama 3.1 8B)
      3. OpenRouter Tier (GPT-OSS -> Qwen 2.5 72B -> Llama 3.3 70B)
      4. Google Gemini Safety Net (gemini-3.5-flash-lite -> gemini-3.8-flash)
      5. Local Deterministic Rule Fallback (if all network providers fail)

    Safe Failover Contract:
    - Buffers the initial 15 tokens from a provider.
    - If provider errors or yields empty stream before buffering completes:
      Catch exception, log fallback reason, and switch to next provider (zero partial text sent to client).
    - If provider errors AFTER streaming begins (chunks_yielded > 0):
      Apply safe termination (trim to terminal punctuation). Do NOT switch models mid-sentence.
    - Yields tuple: (chunk_text, provider_meta).
    """
    httpx_client = custom_httpx_client or get_shared_httpx_client()
    groq_accounts = get_groq_accounts()
    openrouter_key = get_openrouter_key()
    gemini_key = get_gemini_key()

    candidate_providers: List[Dict[str, Any]] = []

    # Tier 1 & 2: Active Groq Accounts
    groq_models_to_try = get_configured_groq_models()
    for acc in groq_accounts:
        for model in groq_models_to_try:
            candidate_providers.append({
                "type": "groq",
                "account_id": acc["account_id"],
                "api_key": acc["api_key"],
                "model": model,
                "url": GROQ_BASE_URL,
                "timeout": 4.0,
            })

    # Tier 3: OpenRouter Tier
    if openrouter_key:
        for model in OPENROUTER_MODELS:
            candidate_providers.append({
                "type": "openrouter",
                "account_id": "OpenRouter",
                "api_key": openrouter_key,
                "model": model,
                "url": OPENROUTER_BASE_URL,
                "timeout": 6.0,
            })

    # Tier 4: Google Gemini Safety Net
    gemini_client = custom_gemini_client
    if gemini_client is None and gemini_key and genai is not None:
        try:
            gemini_client = genai.Client(api_key=gemini_key)
        except Exception as e:
            logger.warning("Failed to initialize Gemini client: %s", e)

    if gemini_client is not None:
        for model in GEMINI_SAFETY_MODELS:
            candidate_providers.append({
                "type": "gemini",
                "account_id": "Google-Gemini",
                "api_key": gemini_key or "configured",
                "model": model,
                "timeout": 8.0,
            })

    execution_attempts = []
    stream_started = False
    full_emitted_text = []
    rate_limited_accounts = set()

    for provider in candidate_providers:
        p_type = provider["type"]
        p_model = provider["model"]
        p_acc = provider["account_id"]
        if p_acc in rate_limited_accounts:
            continue
        call_start = time.time()
        sanitizer = StreamingTagSanitizer()

        initial_buffer: List[str] = []
        buffer_token_count = 0
        MIN_BUFFER_TOKENS = 6  # Buffer enough tokens to validate response and detect reasoning tags

        try:
            # Generate raw token stream
            if p_type in ("groq", "openrouter"):
                raw_gen = _stream_openai_compatible(
                    client=httpx_client,
                    url=provider["url"],
                    api_key=provider["api_key"],
                    model=p_model,
                    prompt=prompt,
                    system_prompt=system_prompt,
                    max_tokens=max_output_tokens,
                    temperature=temperature,
                    timeout_seconds=provider["timeout"],
                )
            elif p_type == "gemini":
                raw_gen = _stream_gemini(
                    client=gemini_client,
                    model=p_model,
                    prompt=prompt,
                    system_prompt=system_prompt,
                    max_tokens=max_output_tokens,
                    temperature=temperature,
                )
            else:
                continue

            async for chunk in raw_gen:
                clean_chunk = sanitizer.feed(chunk)
                if not clean_chunk:
                    continue

                if not stream_started:
                    # In buffering phase
                    initial_buffer.append(clean_chunk)
                    buffer_token_count += len(clean_chunk.split())
                    if buffer_token_count >= MIN_BUFFER_TOKENS or any(p in clean_chunk for p in TERMINAL_PUNCTUATION):
                        # Release buffer and transition to live streaming
                        stream_started = True
                        model_prefix = format_model_prefix(p_model)
                        full_emitted_text.append(model_prefix)
                        yield (model_prefix, {
                            "provider": p_type,
                            "account": p_acc,
                            "model": p_model,
                            "status": "prefix",
                        })
                        for buffered_chunk in initial_buffer:
                            full_emitted_text.append(buffered_chunk)
                            yield (buffered_chunk, {
                                "provider": p_type,
                                "account": p_acc,
                                "model": p_model,
                                "status": "streaming",
                            })
                        initial_buffer.clear()
                else:
                    # Already streaming live
                    full_emitted_text.append(clean_chunk)
                    yield (clean_chunk, {
                        "provider": p_type,
                        "account": p_acc,
                        "model": p_model,
                        "status": "streaming",
                    })

            # Handle flush
            final_chunk = sanitizer.finalize()
            if final_chunk:
                if not stream_started:
                    initial_buffer.append(final_chunk)
                else:
                    full_emitted_text.append(final_chunk)
                    yield (final_chunk, {
                        "provider": p_type,
                        "account": p_acc,
                        "model": p_model,
                        "status": "streaming",
                    })

            if not stream_started and initial_buffer:
                # Stream was short but valid
                stream_started = True
                model_prefix = format_model_prefix(p_model)
                full_emitted_text.append(model_prefix)
                yield (model_prefix, {
                    "provider": p_type,
                    "account": p_acc,
                    "model": p_model,
                    "status": "prefix",
                })
                for buffered_chunk in initial_buffer:
                    full_emitted_text.append(buffered_chunk)
                    yield (buffered_chunk, {
                        "provider": p_type,
                        "account": p_acc,
                        "model": p_model,
                        "status": "streaming",
                    })
                initial_buffer.clear()

            if stream_started:
                # Successfully streamed response from this provider!
                total_text = "".join(full_emitted_text).strip()
                if sanitizer.inside_think:
                    # Unclosed think tag: truncated before valid answer
                    logger.warning("Provider %s (%s) output ended inside thinking tag.", p_type, p_model)

                # Validate word count on pure astrological text without the prefix tag
                content_for_eval = total_text
                prefix_tag = f"[Model: {p_model}]"
                if content_for_eval.startswith(prefix_tag):
                    content_for_eval = content_for_eval[len(prefix_tag):].strip()

                word_eval = validate_response_words(content_for_eval)
                latency_ms = (time.time() - call_start) * 1000
                logger.info(
                    "[ROUTER SUCCESS] %s (%s) generated %d words in %.1f ms.",
                    p_type, p_model, word_eval["word_count"], latency_ms
                )
                yield ("", {
                    "provider": p_type,
                    "account": p_acc,
                    "model": p_model,
                    "status": "completed",
                    "latency_ms": latency_ms,
                    "word_eval": word_eval,
                    "full_text": total_text,
                })
                return  # Single-model completion: terminate cascade immediately

            # If loop exited without streaming any text, treat as empty response failure
            raise ValueError(f"Provider {p_type} ({p_model}) produced empty or reasoning-only response")

        except Exception as e:
            latency_ms = (time.time() - call_start) * 1000
            err_msg = str(e)
            err_lower = err_msg.lower()

            if isinstance(e, httpx.HTTPStatusError):
                status_code = e.response.status_code if e.response else 500
                if status_code == 404 or "model_not_found" in err_lower or "does not exist" in err_lower:
                    logger.warning(
                        "[ROUTER 404 MODEL NOT FOUND] Provider %s model '%s' does not exist or is deprecated (HTTP 404). "
                        "Dynamically failing over to next provider in cascade...",
                        p_type, p_model
                    )
                elif status_code == 400 and ("decommissioned" in err_lower or "deprecated" in err_lower):
                    logger.warning(
                        "[ROUTER MODEL DECOMMISSIONED 400] Provider %s model '%s' is decommissioned. "
                        "Dynamically failing over to next provider in cascade...",
                        p_type, p_model
                    )
                elif is_rate_limit_error(e) or status_code == 429 or "rate_limit" in err_lower:
                    rate_limited_accounts.add(p_acc)
                    if "1" in str(p_acc):
                        logger.warning(
                            "[FAILOVER] Groq Account 1 rate limited, switching to Account 2 in %.2f ms",
                            latency_ms,
                        )
                    elif "2" in str(p_acc):
                        logger.warning(
                            "[FAILOVER] Groq Account 2 rate limited, switching to Tier 3 (Gemini) in %.2f ms",
                            latency_ms,
                        )
                    else:
                        logger.warning(
                            "[ROUTER 429 RATE LIMIT] Provider %s model '%s' rate limited (HTTP 429). "
                            "Dynamically failing over in %.2f ms...",
                            p_type, p_model, latency_ms,
                        )
                else:
                    logger.warning(
                        "[PROVIDER FAILOVER] %s (%s) HTTP %d failed in %.1f ms: %s",
                        p_type, p_model, status_code, latency_ms, err_msg
                    )
            else:
                logger.warning(
                    "[PROVIDER FAILOVER] %s (%s) failed in %.1f ms: %s",
                    p_type, p_model, latency_ms, err_msg
                )

            execution_attempts.append({
                "provider": p_type,
                "model": p_model,
                "error": err_msg,
                "latency_ms": latency_ms,
            })

            if stream_started:
                # CRITICAL: Stream already emitted partial tokens to client!
                # Do NOT switch providers to prevent concatenating incompatible answers.
                logger.error("[SAFE TERMINATION] Stream interrupted after tokens emitted; safely terminating.")
                yield (".", {
                    "provider": p_type,
                    "account": p_acc,
                    "model": p_model,
                    "status": "interrupted",
                    "error": err_msg,
                })
                return

            # Otherwise, failover before sending chunks is safe: proceed to next provider in loop

    # Tier 5: Local Deterministic Rule Fallback (if all network providers failed or unconfigured)
    logger.warning("All LLM providers exhausted or unconfigured. Activating Local Rule Fallback.")
    raw_fallback = (
        local_fallback_text
        or "Based on your chart configuration and active planetary placements, "
           "the astrological indicators show a supportive alignment for this life domain. "
           "Planetary energies encourage thoughtful planning and steady perseverance."
    )
    clean_fallback = raw_fallback.strip()
    if not clean_fallback.startswith("[Source:"):
        formatted_fallback = f"{format_local_badge('Local Database')}{clean_fallback}"
    else:
        formatted_fallback = clean_fallback

    yield (formatted_fallback, {
        "provider": "local_fallback",
        "account": "Local-Rules",
        "model": "deterministic_synthesis",
        "status": "fallback",
        "badge": LOCAL_DB_BADGE,
        "attempts": execution_attempts,
        "full_text": formatted_fallback,
    })


async def generate_cascading_router(
    prompt: str,
    system_prompt: str,
    max_output_tokens: int = 120,
    temperature: float = 0.2,
    session_id: Optional[str] = None,
    history: Optional[List[Dict[str, Any]]] = None,
    custom_httpx_client: Optional[httpx.AsyncClient] = None,
    custom_gemini_client: Optional[Any] = None,
    local_fallback_text: Optional[str] = None,
) -> Tuple[str, Dict[str, Any]]:
    """
    Non-streaming convenience helper for stream_cascading_router.
    Returns (completed_answer_with_badge, decision_metadata).
    """
    accumulated_chunks = []
    final_meta: Dict[str, Any] = {}
    async for chunk, meta in stream_cascading_router(
        prompt=prompt,
        system_prompt=system_prompt,
        max_output_tokens=max_output_tokens,
        temperature=temperature,
        session_id=session_id,
        history=history,
        custom_httpx_client=custom_httpx_client,
        custom_gemini_client=custom_gemini_client,
        local_fallback_text=local_fallback_text,
    ):
        if chunk:
            accumulated_chunks.append(chunk)
        if meta:
            final_meta.update(meta)

    full_text = "".join(accumulated_chunks).strip()
    return full_text, final_meta


class CascadeLLMResult(str):
    """
    Polymorphic result object:
    Acts as a string by default (e.g. response text with provenance tag),
    while also allowing tuple unpacking: (text, metadata).
    """
    def __new__(cls, text: str, meta: Optional[Dict[str, Any]] = None):
        obj = str.__new__(cls, text)
        obj.meta = meta or {}
        return obj

    def __iter__(self):
        yield str(self)
        yield self.meta


async def _call_openai_compatible_endpoint(
    client: httpx.AsyncClient,
    url: str,
    api_key: str,
    model: str,
    prompt: str,
    system_prompt: Optional[str] = None,
    max_tokens: int = 150,
    temperature: float = 0.2,
    timeout_seconds: float = 5.0,
) -> str:
    """Non-streaming direct execution against OpenAI-compatible REST endpoints (e.g. Groq)."""
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
        "User-Agent": "Astro-AI-Chatbot/1.0",
    }
    messages = []
    if system_prompt:
        messages.append({"role": "system", "content": system_prompt})
    messages.append({"role": "user", "content": prompt})

    payload = {
        "model": model,
        "messages": messages,
        "max_tokens": max_tokens,
        "temperature": temperature,
        "stream": False,
    }

    req_timeout = httpx.Timeout(
        connect=2.0,
        read=timeout_seconds,
        write=2.0,
        pool=2.0,
    )

    resp = await client.post(url, json=payload, headers=headers, timeout=req_timeout)
    if resp.status_code != 200:
        error_text = resp.text[:300]
        raise httpx.HTTPStatusError(
            f"HTTP {resp.status_code} from {model}: {error_text}",
            request=resp.request,
            response=resp,
        )

    data = resp.json()
    choices = data.get("choices", [])
    if choices:
        msg = choices[0].get("message", {})
        content = msg.get("content", "")
        sanitizer = StreamingTagSanitizer()
        cleaned = sanitizer.feed(content) + sanitizer.flush()
        return cleaned.strip()
    return ""


